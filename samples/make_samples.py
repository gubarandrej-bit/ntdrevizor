def plan_dxf():
    import ezdxf

    doc = ezdxf.new("R2010")
    doc.layers.add("КАБЕЛЬ_ЭОМ")
    msp = doc.modelspace()
    msp.add_lwpolyline([(0, 0), (10, 0), (10, 20)], dxfattribs={"layer": "КАБЕЛЬ_ЭОМ"})
    msp.add_text("ЩО", dxfattribs={"height": 0.5}).set_placement((0, 0.3))
    msp.add_text("Светильники", dxfattribs={"height": 0.5}).set_placement((10, 20.3))
    doc.saveas(ROOT / "plan_eom.dxf")


